CREATE TABLE fato_geracao_horaria (
    sk_tempo                  INTEGER       NOT NULL REFERENCES dim_tempo (sk_tempo),
    sk_usina                  INTEGER       NOT NULL REFERENCES dim_usina (sk_usina),
    sk_fonte                  INTEGER       NOT NULL REFERENCES dim_fonte_energia (sk_fonte),
    sk_submercado             INTEGER       NOT NULL REFERENCES dim_submercado (sk_submercado),
    sk_tipo_parada            INTEGER       NOT NULL DEFAULT -1 REFERENCES dim_tipo_parada (sk_tipo_parada),

    energia_gerada_mwh        NUMERIC(12,3) NOT NULL,
    energia_bruta_origem_mwh  NUMERIC(12,3),
    disponibilidade_mw        NUMERIC(8,2)  NOT NULL,
    potencia_instalada_mw     NUMERIC(8,2)  NOT NULL,
    pld_hora_r_mwh            NUMERIC(10,2) NOT NULL,
    receita_pld_brl           NUMERIC(14,2) NOT NULL,
    receita_bruta_origem_brl  NUMERIC(14,2),

    flag_em_parada            BOOLEAN       NOT NULL DEFAULT FALSE,
    flag_registro_tratado     BOOLEAN       NOT NULL DEFAULT FALSE,
    tipo_tratamento_qualidade VARCHAR(50)   NOT NULL DEFAULT 'ORIGINAL_VALIDO',
    atraso_recebimento_horas  NUMERIC(10,2),
    CONSTRAINT pk_fato_geracao_horaria PRIMARY KEY (sk_tempo, sk_usina)
);

CREATE INDEX idx_fato_geracao_usina ON fato_geracao_horaria (sk_usina);
CREATE INDEX idx_fato_geracao_sub   ON fato_geracao_horaria (sk_submercado);
CREATE INDEX idx_fato_geracao_fonte ON fato_geracao_horaria (sk_fonte);

CREATE TABLE fato_pld_horario (
