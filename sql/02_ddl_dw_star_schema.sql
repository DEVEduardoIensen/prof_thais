CREATE TABLE dim_tempo (
    sk_tempo             INTEGER      NOT NULL,
    data_hora            TIMESTAMP,
    data                 DATE,
    ano                  SMALLINT,
    semestre             SMALLINT,
    trimestre            SMALLINT,
    mes                  SMALLINT,
    nome_mes             VARCHAR(20),
    ano_mes              CHAR(7),
    dia                  SMALLINT,
    dia_do_ano           SMALLINT,
    hora                 SMALLINT,
    dia_semana_num       SMALLINT,
    nome_dia_semana      VARCHAR(20),
    flag_fim_de_semana   BOOLEAN,
    flag_feriado         BOOLEAN,
    nome_feriado         VARCHAR(60),
    tipo_feriado         VARCHAR(25),
    flag_dia_util        BOOLEAN,
    estacao_ano          VARCHAR(20),
    periodo_hidrologico  VARCHAR(25),
    patamar_carga        VARCHAR(15),
    CONSTRAINT pk_dim_tempo PRIMARY KEY (sk_tempo)
);

CREATE INDEX idx_dim_tempo_data_hora ON dim_tempo (data_hora);
CREATE INDEX idx_dim_tempo_ano_mes   ON dim_tempo (ano, mes);

