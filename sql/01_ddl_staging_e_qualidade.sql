CREATE TABLE IF NOT EXISTS raw_pld_horario (
    id_raw          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_referencia  SMALLINT      NOT NULL,
    resource_id     VARCHAR(60)   NOT NULL,
    mes_referencia   VARCHAR(20),
    dia              VARCHAR(30),
    hora            VARCHAR(20),
    submercado      VARCHAR(30),
    pld_hora_raw    VARCHAR(40),
    payload_json    TEXT          NOT NULL,
    origem          VARCHAR(80)   NOT NULL DEFAULT 'CCEE_CKAN_API',
    extraido_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_raw_pld_ano ON raw_pld_horario (ano_referencia);

CREATE TABLE IF NOT EXISTS pld_horario_tratado (
    data_hora       TIMESTAMP     NOT NULL,
    cod_submercado  CHAR(2)       NOT NULL,
    submercado_ccee VARCHAR(30)   NOT NULL,
    ano             SMALLINT      NOT NULL,
    mes             SMALLINT      NOT NULL,
    hora            SMALLINT      NOT NULL,
    pld_r_mwh       NUMERIC(10,2) NOT NULL,
    flag_valido     BOOLEAN       NOT NULL DEFAULT TRUE,
    origem          VARCHAR(80)   NOT NULL DEFAULT 'CCEE_CKAN_API',
    extraido_em     TIMESTAMP     NOT NULL,
    tratado_em      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_pld_horario_tratado PRIMARY KEY (data_hora, cod_submercado)
);

CREATE INDEX IF NOT EXISTS idx_pld_tratado_sub_data ON pld_horario_tratado (cod_submercado, data_hora);

CREATE TABLE IF NOT EXISTS raw_clima_horario (
    id_raw                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usina               VARCHAR(12)   NOT NULL,
    latitude_consulta       NUMERIC(9,6)  NOT NULL,
    longitude_consulta      NUMERIC(9,6)  NOT NULL,
    data_hora_iso           VARCHAR(30)   NOT NULL,
    shortwave_radiation_raw VARCHAR(30),
    wind_speed_10m_raw      VARCHAR(30),
    wind_speed_100m_raw     VARCHAR(30),
    temperature_2m_raw      VARCHAR(30),
    precipitation_raw       VARCHAR(30),
    origem                  VARCHAR(80)   NOT NULL DEFAULT 'OPEN_METEO_ARCHIVE_API',
    extraido_em             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_raw_clima_usina ON raw_clima_horario (cod_usina, data_hora_iso);

CREATE TABLE IF NOT EXISTS clima_horario_tratado (
    cod_usina         VARCHAR(12)   NOT NULL,
    data_hora         TIMESTAMP     NOT NULL,
    latitude_real     NUMERIC(9,6)  NOT NULL,
    longitude_real    NUMERIC(9,6)  NOT NULL,
    radiacao_wm2      NUMERIC(8,2),
    vento_10m_kmh     NUMERIC(8,2),
    vento_100m_kmh    NUMERIC(8,2),
    temperatura_c     NUMERIC(6,2),
    precipitacao_mm   NUMERIC(8,2),
    origem            VARCHAR(80)   NOT NULL DEFAULT 'OPEN_METEO_ARCHIVE_API',
    extraido_em       TIMESTAMP     NOT NULL,
    tratado_em        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_clima_horario_tratado PRIMARY KEY (cod_usina, data_hora)
);

