SELECT COUNT(*) AS total_horas
FROM generate_series(TIMESTAMP '2025-01-01 00:00:00',
                     TIMESTAMP '2025-12-31 23:00:00',
                     INTERVAL '1 hour') AS t(data_hora);

INSERT INTO medicao_geracao (id_usina, data_hora, energia_mwh, disponibilidade_mw, recebido_em)
SELECT
    b.id_usina,
    b.data_hora,
    ROUND((b.potencia_mw * GREATEST(0, LEAST(0.98,
        CASE b.cod_fonte
          WHEN 'UFV' THEN
               GREATEST(0, SIN(PI() * (b.h - 6) / 12))
             * (1 + 0.08 * COS(2 * PI() * (b.doy - 15) / 365))
             * (0.55 + 0.45 * b.ruido)
             * 0.88
          WHEN 'EOL' THEN
               (CASE b.cod_submercado WHEN 'NE' THEN 0.30 ELSE 0.22 END)
             + (CASE b.cod_submercado WHEN 'NE' THEN 0.35 ELSE 0.18 END)
               * (1 + COS(2 * PI() * (b.doy - 242) / 365)) / 2
             + 0.12 * COS(2 * PI() * (b.h - 2) / 24)
             + 0.35 * (b.ruido - 0.5)
          WHEN 'UHE' THEN
               (CASE b.cod_submercado WHEN 'S' THEN 0.58 ELSE 0.52 END)
             + (CASE b.cod_submercado WHEN 'S' THEN 0.08 ELSE 0.25 END)
               * COS(2 * PI() * (b.doy - 45) / 365)
             + 0.10 * SIN(PI() * (b.h - 6) / 18)
               * (CASE WHEN b.h BETWEEN 6 AND 23 THEN 1 ELSE 0 END)
             + 0.08 * (b.ruido - 0.5)
          WHEN 'PCH' THEN
               0.60 + 0.15 * COS(2 * PI() * (b.doy - 30) / 365)
             + 0.10 * (b.ruido - 0.5)
          WHEN 'BIO' THEN
               CASE WHEN b.mes BETWEEN 4 AND 11
                    THEN 0.78 + 0.15 * (b.ruido - 0.5)
                    ELSE 0.02 + 0.03 * b.ruido END
          WHEN 'UTE' THEN
               CASE WHEN b.h BETWEEN 17 AND 21 AND b.ruido > 0.25 THEN 0.84 + 0.08 * b.ruido
                    WHEN b.mes BETWEEN 8 AND 11 AND b.ruido > 0.40 THEN 0.76 + 0.08 * b.ruido
                    WHEN b.ruido > 0.93                         THEN 0.60 + 0.05 * b.ruido
                    ELSE 0 END
        END
    )))::NUMERIC, 3) AS energia_mwh,
    b.potencia_mw AS disponibilidade_mw,
    b.data_hora + (65 + FLOOR(b.ruido * 40)) * INTERVAL '1 minute' AS recebido_em
FROM (
    SELECT u.id_usina, u.potencia_mw, u.cod_submercado, f.cod_fonte,
           t.data_hora,
           EXTRACT(HOUR  FROM t.data_hora)::INT AS h,
           EXTRACT(MONTH FROM t.data_hora)::INT AS mes,
           EXTRACT(DOY   FROM t.data_hora)::INT AS doy,
           ((('x' || SUBSTR(MD5(u.cod_usina || '|' || TO_CHAR(t.data_hora, 'YYYY-MM-DD HH24:MI:SS')), 1, 8))
              ::BIT(32)::BIGINT % 10000) / 10000.0)::DOUBLE PRECISION AS ruido
    FROM usina u
    JOIN fonte_energia f ON f.id_fonte = u.id_fonte
    CROSS JOIN generate_series(TIMESTAMP '2025-01-01 00:00:00',
                               TIMESTAMP '2025-12-31 23:00:00',
                               INTERVAL '1 hour') AS t(data_hora)
) AS b
ORDER BY b.id_usina, b.data_hora;

UPDATE medicao_geracao m
SET energia_mwh        = 0,
    disponibilidade_mw = 0
FROM parada_usina p
WHERE p.id_usina = m.id_usina
  AND m.data_hora BETWEEN p.inicio AND p.fim;

SELECT u.cod_usina, u.nome,
       COUNT(*)                                   AS horas,
       ROUND(SUM(m.energia_mwh) / 1000, 1)        AS gwh_ano,
       ROUND(SUM(m.energia_mwh) / (u.potencia_mw * 8760) * 100, 1) AS fator_capacidade_pct
FROM medicao_geracao m
JOIN usina u ON u.id_usina = m.id_usina
GROUP BY u.id_usina, u.cod_usina, u.nome, u.potencia_mw
ORDER BY u.id_usina;

